-- Esquema del grafo del campus: puntos, tramos y administradores.
-- El grafo es no dirigido: cada tramo se guarda una sola vez y se recorre en ambos sentidos.

-- PUNTO: entradas del campus, entradas de edificio y cruces del recorrido
CREATE TABLE punto (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre        VARCHAR(120)          NOT NULL,
    tipo          VARCHAR(20)           NOT NULL,
    edificio      VARCHAR(60),
    -- Solo los puntos seleccionables aparecen como origen o destino; el resto sirve de paso
    seleccionable BOOLEAN               NOT NULL DEFAULT FALSE,
    ubicacion     geometry(Point, 4326) NOT NULL,
    CONSTRAINT uk_punto_nombre UNIQUE (nombre),
    CONSTRAINT ck_punto_tipo CHECK (tipo IN ('ENTRADA_CAMPUS', 'ENTRADA_EDIFICIO', 'CRUCE')),
    -- Una entrada de edificio siempre indica su edificio; una entrada del campus no pertenece a ninguno
    CONSTRAINT ck_punto_edificio CHECK (
        (tipo <> 'ENTRADA_EDIFICIO' OR edificio IS NOT NULL)
        AND (tipo <> 'ENTRADA_CAMPUS' OR edificio IS NULL)),
    -- Un cruce nunca se puede elegir como origen o destino
    CONSTRAINT ck_punto_cruce_no_seleccionable CHECK (tipo <> 'CRUCE' OR NOT seleccionable)
);

CREATE INDEX ix_punto_ubicacion ON punto USING GIST (ubicacion);

-- TRAMO: une dos puntos; la longitud en metros la calcula PostGIS (ver triggers abajo)
CREATE TABLE tramo (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- RESTRICT: para borrar un punto primero se deben borrar sus tramos
    punto_inicial_id BIGINT           NOT NULL REFERENCES punto (id) ON DELETE RESTRICT,
    punto_final_id   BIGINT           NOT NULL REFERENCES punto (id) ON DELETE RESTRICT,
    condicion        VARCHAR(20)      NOT NULL,
    longitud_m       DOUBLE PRECISION NOT NULL,
    CONSTRAINT ck_tramo_condicion CHECK (condicion IN ('PLANO', 'RAMPA', 'PENDIENTE_FUERTE', 'ESCALERAS')),
    CONSTRAINT ck_tramo_sin_bucle CHECK (punto_inicial_id <> punto_final_id)
);

-- Un solo tramo entre los mismos dos puntos, sin importar el orden (A-B equivale a B-A)
CREATE UNIQUE INDEX ux_tramo_par ON tramo (
    LEAST(punto_inicial_id, punto_final_id),
    GREATEST(punto_inicial_id, punto_final_id));

CREATE INDEX ix_tramo_punto_inicial ON tramo (punto_inicial_id);
CREATE INDEX ix_tramo_punto_final ON tramo (punto_final_id);

-- ADMINISTRADOR: solo la tabla; los usuarios se crean en la etapa de seguridad
CREATE TABLE administrador (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    correo             VARCHAR(254) NOT NULL,
    contrasena_cifrada VARCHAR(100) NOT NULL,
    CONSTRAINT uk_administrador_correo UNIQUE (correo)
);

-- LONGITUD DE LOS TRAMOS
-- Una columna generada no puede leer otras tablas, por eso se usan triggers.
-- La distancia se mide sobre geography (esferoide WGS84), así el resultado queda en metros.
CREATE FUNCTION fn_longitud_tramo(p_inicial BIGINT, p_final BIGINT) RETURNS DOUBLE PRECISION
    LANGUAGE sql STABLE AS
$$
SELECT ST_Distance(a.ubicacion::geography, b.ubicacion::geography)
FROM punto a, punto b
WHERE a.id = p_inicial AND b.id = p_final
$$;

-- Antes de guardar un tramo se calcula su longitud; cualquier valor enviado a mano se descarta
CREATE FUNCTION fn_tramo_calcular_longitud() RETURNS TRIGGER
    LANGUAGE plpgsql AS
$$
BEGIN
    NEW.longitud_m := fn_longitud_tramo(NEW.punto_inicial_id, NEW.punto_final_id);
    RETURN NEW;
END;
$$;

CREATE TRIGGER tg_tramo_longitud
    BEFORE INSERT OR UPDATE ON tramo
    FOR EACH ROW EXECUTE FUNCTION fn_tramo_calcular_longitud();

-- Si un punto se mueve, se recalculan los tramos que lo tocan
CREATE FUNCTION fn_punto_recalcular_tramos() RETURNS TRIGGER
    LANGUAGE plpgsql AS
$$
BEGIN
    UPDATE tramo
    SET longitud_m = fn_longitud_tramo(punto_inicial_id, punto_final_id)
    WHERE punto_inicial_id = NEW.id OR punto_final_id = NEW.id;
    RETURN NULL;
END;
$$;

CREATE TRIGGER tg_punto_ubicacion
    AFTER UPDATE OF ubicacion ON punto
    FOR EACH ROW
    WHEN (NOT ST_Equals(OLD.ubicacion, NEW.ubicacion))
    EXECUTE FUNCTION fn_punto_recalcular_tramos();
